%% Toolbox paths

path_toolbox_sitau = '..\Toolbox_sitau2\';
%path_bin_folder = 'BIN_NOBF\'; %No beamforming version (only for FUS)
path_bin_folder = 'BIN\'; %Generic version with beamforming

addpath(path_toolbox_sitau)

clc

%% OPEN SYSTEM
% (emulates_sitau2 = false) -> No Hardware mode disabled, it is necessary 
%       to connect the hardware to use the library.
% (emulates_sitau2 = true) -> No Hardware mode activated, it is not 
%       necessary to connect the hardware to use the library, the 
%       library functions do not access the hardware, the data received by 
%       the hardware is synthetically generated by the library.
emulates_sitau2 = false;


result = OpenSys ([path_toolbox_sitau path_bin_folder], '192.168.2.10', 55902, 50460, 0, emulates_sitau2);
if (result < 0)
	CloseSys();
	return;
end


%% SYSTEM CONFIGURATION 

xmlFile = 'SITAU2_GE_RF.XML';

% [valid, withWarnings, performance] = Validate_XMLConfig(xmlFile);
 
result = FUS_LoadXMLFileConfig(xmlFile);
if (result < 0)
    CloseSys();
    return;
end

result = ST2_SetPulseAmplitude(0);
if (result < 0)
    CloseSys();
    return;
end

%% Prueba de lectura de datos
fprintf('Acquisition mode: %d\n', ST2_GetAcquisitionMode());
fprintf('Acquisition type: %d\n', ST2_GetAcquisitionType());
fprintf('Channels: %d\n', ST2_GetChannelsNumber());
fprintf('Probe elements: %d\n', ST2_GetProbeElementNumber());
fprintf('Focal laws: %d\n', ST2_GetFocalLawNumber());
fprintf('PWI angles: %d\n', ST2_MC_GetPlaneWaveImaging_AnglesNumber());

%% Get parameters from system

%burst_number = ST2_GetBurstsNumber(); %CUIDADO QUE PUEDE LLEVAR A ERROR
%number_of_fmc_per_burst=ST2_GetFMCMatrixBurstNumber();
acquisition_mode_continuous = ST2_GetAcquisitionMode();

%burst_size = ST2_MC_GetFMCMatrixSize() * ST2_GetFMCMatrixBurstNumber();

mc_size =    ST2_MC_GetMatrixCaptureSize();
n_samples =     ST2_GetAScanDataNumber();
n_channels=     ST2_GetProbeElementNumber();
n_focal_law = ST2_GetFocalLawNumber();
fnyq=62.5/2;

% n_samples = ST2_GetAScanDataNumber();
% n_channels=ST2_GetProbeElementNumber();
%n_images_burst=ST2_GetFMCMatrixBurstNumber();
[error,angles] = ST2_MC_GetPlaneWaveImaging_Angles_rad();
n_angles = length(angles);

%burst_size = n_samples*n_channels*n_focal_law*number_of_fmc_per_burst;
ptr_data = libpointer('int16Ptr', 1:mc_size);

%% Acauisition loop

% Prepare figure
if ~exist('h_figure', 'var') || ~isvalid(h_figure)
    h_figure = figure('visible','on');
    hButtonStop = uicontrol('Style', 'pushbutton', 'String', 'STOP',...
        'Position', [20 20 100 40], 'Callback', 'setappdata(gcbf, ''stopFlag'', 1)');
    set(h_figure, 'CloseRequestFcn', @closeFigCallback);
    imagesc(rand(5)); colormap gray;
end
setappdata(h_figure, 'stopFlag', 0);

burst_counter = 0;
timeout_ms = 1000;


result = ST2_Start(1);
if (result < 0)
    ST2_CloseSys();
    return;
end

flag_end = false;

try
    while (flag_end == false)

    [result, rf, idx_burst] = ST2_MC_GetBuffer_LastMatrixCapture (ptr_data, mc_size);
    if (result < 0)
        fprintf('Error ST2_MC_GetBuffer_LastMatrixCapture: %s\n', ST2_ErrorText(result)); % Describe el resultado real sin usar n_acq_images, que no existe.
        flag_end = true;
    else    
        if (result > 0)
            burst_counter = burst_counter + 1;

            a=reshape(rf,n_samples,n_channels,n_focal_law,1); %aqui estaba n_angles en lugar de n_focal_law
            %imagesc(a(:,:,2,1));
            for focal_law=1:n_focal_law
                imagesc(a(:,:,focal_law,1));
                pause(0.1)
            end
                       
        else
            fprintf("\rNº Imagens adquiridas: 0");
        
        end
    end
    drawnow;
    
    % Check if STOP button was pressed
    if getappdata(h_figure, 'stopFlag') == 1
        flag_end = true;
    end

    % Check if the window was clossed
    if getappdata(h_figure, 'isClosed') == 1
        flag_end = true;
    end
        
end
catch ME
    fprintf('Error inside acquisition loop line %d \n',ME.stack(end).line);
    disp(ME.message);               % Muestra el mensaje de error
end

%% STOP  ACQUISITION

ST2_Stop();

CloseSys();

%% Auxiliar function when figure is closed

function closeFigCallback(src, ~)
setappdata(src, 'isClosed', 1);  % Cambiar la variable de control
delete(src);  % Cerrar la figura
end
