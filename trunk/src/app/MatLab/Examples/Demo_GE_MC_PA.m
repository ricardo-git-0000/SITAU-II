
%% Toolboxes path

path_toolbox_sitau = '..\Toolbox_sitau2\';
addpath(path_toolbox_sitau)

clc

%% ACQUISITION TYPES
ACQUISITION_TYPE_MC = 0;
ACQUISITION_TYPE_PA = 1;
ACQUISITION_TYPE_TFM = 2;

%% ACQUISITION MODES
ACQUISITION_MODE_FIXED = 0;
ACQUISITION_MODE_CONTINOUS = 1;

%% OPEN THE SYSTEM
% (emulates_sitau2 = false) -> No Hardware mode disabled, it is necessary
%       to connect the hardware to use the library.
% (emulates_sitau2 = true) -> No Hardware mode activated, it is not
%       necessary to connect the hardware to use the library, the
%       library functions do not access the hardware, the data received by
%       the hardware is synthetically generated by the library.
emulates_sitau2 = false;

result = OpenSys ([path_toolbox_sitau 'BIN\'], '192.168.2.10', 55902, 50460, 0, emulates_sitau2);
if (result < 0)
    CloseSys();
    return;
end

%% FORMAT DATA CONFIGURATION
% 0 -> UT data are sorted
% 1 -> UT data are not sorted, the format is the one received from the equipment.
result = ST2_SetHWFormatData(0);
if (result < 0)
    ST2_CloseSys();
    return;
end

%% SYSTEM CONFIGURATION
xmlFile = 'SITAU2_GE.XML';

% [valid, withWarnings, performance] = Validate_XMLConfig(xmlFile);
result = ST2_LoadXMLFileConfig(xmlFile);

if (result < 0)
    CloseSys();
    return;
end

result = ST2_SetPulseAmplitude(30);
if (result < 0)
    CloseSys();
    return;
end

result = ST2_SetPRF(1000);
if (result < 0)
    CloseSys();
    return;
end

%% Set Acquisitions Number

result = ST2_SetAcquisitionsNumber(10, 1);
if (result < 0)
    ST2_CloseSys();
    return;
end

%% Set Acquisition Mode

result = ST2_SetAcquisitionMode(ACQUISITION_MODE_FIXED);
if (result < 0)
    ST2_CloseSys();
    return;
end

n_cycles = 1;
for i=1:n_cycles

    %% Set Acquisition Type

    result = ST2_SetAcquisitionType(ACQUISITION_TYPE_MC);
    if (result < 0)
        ST2_CloseSys();
        return;
    end
    
    % result = ST2_MC_SetFullMatrixCapture();
    % if (result < 0)
    %     ST2_CloseSys();
    %     return;
    % end

    result = ST2_MC_SetPlaneWaveImaging_Angles_deg(-5:1:5, 11);
    if (result < 0)
        CloseSys();
        return;
    end    
    
    %% Start Adquisition

    AcquisitionData();
    
    result = ST2_MC_SetPlaneWaveImaging(-20, 1, 20);
    if (result < 0)
        ST2_CloseSys();
        return;
    end
    
    %% Start Adquisition

    AcquisitionData();

    %% Set Acquisition Type

    result = ST2_SetAcquisitionType(ACQUISITION_TYPE_PA);
    if (result < 0)
        ST2_CloseSys();
        return;
    end
    
    result = ST2_PA_SetLinearScanConfig(1, 16, 0, 127, 0);
    if (result < 0)
        CloseSys();
        return;
    end

    %% Start Adquisition

    AcquisitionData();

    result = ST2_PA_SetAngularScanConfig(1, 128, 0, -45, 45);
    if (result < 0)
        CloseSys();
        return;
    end

    %% Start Adquisition

    AcquisitionData();

end

%% Stop acquisition and close connection

ST2_Stop();
CloseSys();

