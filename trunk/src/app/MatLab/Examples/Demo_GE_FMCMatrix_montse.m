%function  Demo_GE_FMCMatrix.m ()
% 
%**************************************************************************
%*                      API_PCIe.DLL TEST MODE                            *
%* Version    : 1.0                                                       *
%* Author     : Ricardo González.                                         *
%* Copyright  : DASEL                                                     * 
%*                                                                        *
%**************************************************************************
%*          EXAMPLE OF USE OF THE TOOLBOX SITAU2 (API_PCIe.DLL)           *
%*                                                                        *
%* In this example, the use of the MatLab toolbox functions required      *
%* to perform the acquisition by reading 'FMC Matrix'.                    *
%*                                                                        *
%**************************************************************************

path_toolbox_sitau = '..\Toolbox_sitau2\';
addpath(path_toolbox_sitau)

clc

paint_all_focal_laws = true;

% OPEN THE SYSTEM
% ---------------

% (emulates_sitau2 = false) -> No Hardware mode disabled, it is necessary 
%       to connect the hardware to use the library.
% (emulates_sitau2 = true) -> No Hardware mode activated, it is not 
%       necessary to connect the hardware to use the library, the 
%       library functions do not access the hardware, the data received by 
%       the hardware is synthetically generated by the library.
emulates_sitau2 = false;

result = OpenSys ([path_toolbox_sitau 'BIN\'], '192.168.2.10', 55902, 50460, 0, emulates_sitau2);
if (result < 0)
	CloseSys();
	return;
end

% CONFIGURATION OF THE SYSTEM
% ---------------------------

result = ST2_LoadXMLFileConfig('SITAU2_GE.XML');
if (result < 0)
    CloseSys();
    return;
end

result = ST2_SetPulseAmplitude(40);
if (result < 0)
    CloseSys();
    return;
end

result = ST2_MC_SetPlaneWaveImaging(-5,2,5);
if (result < 0)
    CloseSys();
    return;
end
% 
% result = ST2_MC_SetPlaneWaveImaging_Angles_deg([-12 -5 0 5 12], 5);
% if (result < 0)
%     CloseSys();
%     return;
% end

% MEMORY RESERVE FOR THE ENTIRE ACQUISITION
% -----------------------------------------

%image_size = ST2_MC_GetFMCMatrixSize();
image_size = ST2_MC_GetMatrixCaptureSize();
fl_size = ST2_MC_GetSingleImageSize();
n_samples = ST2_GetAScanDataNumber();
n_focal_laws = ST2_GetFocalLawNumber();
n_ch = ST2_GetChannelsNumber();
n_images = ST2_GetAcquisitionsNumber();
ptr_data = libpointer('int16Ptr', 1:image_size);
h_figure = figure('visible','on');
img = reshape(zeros(1,fl_size), n_samples, n_ch);
imagesc(img);
colorbar;

% START OF ACQUISITION
% --------------------

result = ST2_Start(1);
if (result < 0)
    CloseSys();
    return;
end

% ACQUIRING LOOP
% --------------

flag_end = false;
flag_abort = false;
i_img = 0;
while (flag_end == false && flag_abort == false)
   % [result data i_img] = ST2_MC_GetBuffer_LastFMCMatrix (ptr_data, image_size);
    [result data] = ST2_MC_GetBuffer_MatrixCapture (ptr_data, image_size, i_img);
    if (result < 0)
        flag_end = true;
    else
        if result > 0
            if paint_all_focal_laws
                img = reshape(data, n_samples, n_ch * n_focal_laws);
                imagesc(img);
                colorbar;
                title(['After Acquiring >>> Aquisition: ' int2str(i_img+1) '/' int2str(n_images) ]);
                xlabel('Channel')
                ylabel('samples')   
                % caxis([0 1000])
                drawnow;
            else           
                for i_fl=1:n_focal_laws
                    offset = fl_size * (i_fl - 1) + 1;
                    if offset + fl_size <= image_size + 1            
                        img = reshape(data(offset:offset+fl_size-1), n_samples, n_ch);
                        imagesc(img);
                        colorbar;
                        title(['Acquiring... >>> Acquisition: ' int2str(i_img+1) '/' int2str(n_images) ' - Focal Law ' int2str(i_fl) '/' int2str(n_focal_laws) ]);
                        xlabel('Channel')
                        ylabel('samples')   
                        drawnow;
                    end
                    if ~ishghandle(h_figure)
%                     if isdeleted(h_figure) == true
                        flag_abort = true;
                        break;
                    end
                end
                if (i_img >= (n_images - 1))
                    flag_end = true;
                end
            end
            i_img = i_img+1;
            if (i_img >= n_images)
                flag_end = true;
            end
        end
        drawnow;
    end
    if (flag_abort == false)
        %flag_abort = isdeleted(h_figure) == true;
        flag_abort = ~ishghandle(h_figure);
    end
end

% AFTER ACQUIRING LOOP
% --------------------
if (flag_abort == false)
    for i_img=1:n_images   
%        [result data] = ST2_MC_GetBuffer_FMCMatrix (ptr_data, image_size, i_img-1);
        [result data] = ST2_MC_GetBuffer_MatrixCapture (ptr_data, image_size, i_img-1);        
        if result > 0
            if paint_all_focal_laws
                img = reshape(data, n_samples, n_ch * n_focal_laws);
                imagesc(img);
                colorbar;
                title(['After Acquiring >>> Aquisition: ' int2str(i_img) '/' int2str(n_images) ]);
                xlabel('Channel')
                ylabel('samples')   
                drawnow;
            else
                for i_fl=1:n_focal_laws
                    offset = fl_size * (i_fl - 1) + 1;
                    if offset + fl_size <= image_size + 1            
                        img = reshape(data(offset:offset+fl_size-1), n_samples, n_ch);
                        imagesc(img);
                        colorbar;
                        title(['After Acquiring >>> Aquisition: ' int2str(i_img) '/' int2str(n_images) ' - Focal Law ' int2str(i_fl) '/' int2str(n_focal_laws) ]);
                        xlabel('Channel')
                        ylabel('samples')   
                        drawnow;
                    end
                    if ~ishghandle(h_figure)
%                     if isdeleted(h_figure) == true
                        break;
                    end
                end
            end
        end
        if ~ishghandle(h_figure)
%         if isdeleted(h_figure) == true
            break;
        end
    end
end

% STOP OF ACQUISITION
% -------------------

ST2_Stop();

% CLOSE CONNECTION
% ----------------

CloseSys();

